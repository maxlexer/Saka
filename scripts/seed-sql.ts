import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { catalogRows, type CatalogFile } from "./lib/catalog-rows.ts";

const OUT = "supabase/migrations/20261019000100_catalog_seed.sql";
const text = (value: string) => `'${value.replaceAll("'", "''")}'`;
const list = (values: string[]) => (values.length ? `array[${values.map(text).join(", ")}]` : "'{}'::text[]");

export function seedSql(file: CatalogFile) {
  const { products, prices } = catalogRows(file);
  const rows = products.map((p) =>
    `  (${[text(p.slug), text(p.name), text(p.family), text(p.description), list(p.notes_top), list(p.notes_heart), list(p.notes_base), text(p.mood), text(p.occasion), list(p.vibes), list(p.occasions), p.available, p.sort].join(", ")})`,
  );
  return [
    "-- Generated by scripts/seed-sql.ts from supabase/seed/catalog.json. Do not edit by hand.",
    "insert into products (slug, name, family, description, notes_top, notes_heart, notes_base, mood, occasion, vibes, occasions, available, sort) values",
    rows.join(",\n"),
    "on conflict (slug) do nothing;",
    "",
    "insert into size_prices (size_ml, price_usd) values",
    prices.map((r) => `  (${r.size_ml}, ${r.price_usd})`).join(",\n"),
    "on conflict (size_ml) do nothing;",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, seedSql(JSON.parse(readFileSync("supabase/seed/catalog.json", "utf8"))));
  console.log(`wrote ${OUT}`);
}
